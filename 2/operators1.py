#arithmetic operators

x= int(input("Enter the value : "))
y= int(input("Enter the value : "))

print(x+y)
print(x-y)
print(x*y)
print(x/y)
print(x%y)
print(x**y)

#comparison operators

print(x==y)
print(x>=y)
print(x!=y)
print(x<=y)
print(x!=y)
print(x<y)

#logical operators

print("and operator result is : ", x>y and x>y)
print("Or operator result is : ", x>y or x>y)
print("not operator result is : ", not(x>y)) 